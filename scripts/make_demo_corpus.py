FONT_CANDIDATES = [
    Path(r"C:\Windows\Fonts\arial.ttf"),
    Path(r"C:\Windows\Fonts\DejaVuSans.ttf"),
]
BOLD_CANDIDATES = [
    Path(r"C:\Windows\Fonts\arialbd.ttf"),
    Path(r"C:\Windows\Fonts\DejaVuSans-Bold.ttf"),
]


def register_fonts() -> tuple[str, str]:
    regular = next((path for path in FONT_CANDIDATES if path.exists()), None)
    bold = next((path for path in BOLD_CANDIDATES if path.exists()), None)
    if regular is None:
        raise SystemExit("Не найден TTF-шрифт с кириллицей")
    pdfmetrics.registerFont(TTFont("StudyFont", str(regular)))
    if bold:
        pdfmetrics.registerFont(TTFont("StudyFont-Bold", str(bold)))
        return "StudyFont", "StudyFont-Bold"
    return "StudyFont", "StudyFont"


